"""ECDSA signature verification (P4).

Implements SEC 1 v2, section 4.1.4. Every function accepts an optional
``trace`` list and appends human-readable TraceStep entries so the GUI can
show each step to students.

Design rule: verification NEVER raises. Any failed check returns False and the
failing check is recorded as the last trace step, titled "INVALID: <reason>".
"""
from __future__ import annotations

from os import PathLike
from typing import TYPE_CHECKING

from ecdsa_edu.core.curve import is_on_curve, point_add, scalar_mult
from ecdsa_edu.core.field import inv_mod
from ecdsa_edu.core.hashing import hash_file, hash_message
from ecdsa_edu.core.trace import add_step

if TYPE_CHECKING:
    from ecdsa_edu.core.trace import Trace
    from ecdsa_edu.core.types import PublicKey, Signature


def _fmt(v: int) -> str:
    """Decimal for small numbers (readable on toy curves), hex for big ones."""
    return str(v) if v.bit_length() <= 64 else hex(v)


def _fmt_point(P: tuple[int, int] | None) -> str:
    return "O (point at infinity)" if P is None else f"({_fmt(P[0])}, {_fmt(P[1])})"


def _reject(trace: "Trace | None", reason: str, formula: str = "", **values: str) -> bool:
    """Log why the signature is rejected and return False."""
    add_step(trace, f"INVALID: {reason}", formula, **values)
    return False


def _check_inputs(pub: "PublicKey", sig: "Signature", trace: "Trace | None") -> bool:
    """SEC 1 4.1.4 step 1, plus public-key validation. Returns True if all pass."""
    curve = pub.curve
    n = curve.n
    r, s = sig.r, sig.s

    if not isinstance(r, int) or not 1 <= r <= n - 1:
        return _reject(trace, "r out of range", "require 1 <= r <= n-1", r=str(r), n=_fmt(n))
    if not isinstance(s, int) or not 1 <= s <= n - 1:
        return _reject(trace, "s out of range", "require 1 <= s <= n-1", s=str(s), n=_fmt(n))
    add_step(trace, "Check r and s are in range", "1 <= r <= n-1 and 1 <= s <= n-1",
             r=_fmt(r), s=_fmt(s), n=_fmt(n))

    Q = pub.Q
    if Q is None:
        return _reject(trace, "public key is the point at infinity", "require Q != O")
    if not is_on_curve(curve, Q):
        return _reject(trace, "public key is not on the curve",
                       "require y^2 = x^3 + a*x + b (mod p)", Q=_fmt_point(Q))
    if curve.h != 1 and scalar_mult(curve, n, Q) is not None:
        # With cofactor 1 every point on the curve has order n, so this check is
        # only needed for curves with h > 1.
        return _reject(trace, "public key is not in the subgroup generated by G",
                       "require n*Q = O", Q=_fmt_point(Q))
    add_step(trace, "Check the public key", "Q != O and Q is on the curve", Q=_fmt_point(Q))
    return True


def _verify_digest(pub: "PublicKey", e: int, sig: "Signature",
                   trace: "Trace | None" = None) -> bool:
    """Core of SEC 1 4.1.4 once the message hash e is known (steps 4-8).

    Kept separate so tests can use textbook examples with a given e.
    """
    curve = pub.curve
    n, G, Q = curve.n, curve.G, pub.Q
    r, s = sig.r, sig.s

    w = inv_mod(s, n)
    add_step(trace, "Compute w = s^-1 mod n", "w = s^-1 mod n", s=_fmt(s), w=_fmt(w))

    u1 = (e * w) % n
    u2 = (r * w) % n
    add_step(trace, "Compute u1 and u2", "u1 = e*w mod n,  u2 = r*w mod n",
             e=_fmt(e), r=_fmt(r), u1=_fmt(u1), u2=_fmt(u2))

    P1 = scalar_mult(curve, u1, G)
    P2 = scalar_mult(curve, u2, Q)
    X = point_add(curve, P1, P2)
    add_step(trace, "Compute X = u1*G + u2*Q", "X = u1*G + u2*Q",
             u1G=_fmt_point(P1), u2Q=_fmt_point(P2), X=_fmt_point(X))

    if X is None:
        return _reject(trace, "u1*G + u2*Q is the point at infinity", "require X != O")

    v = X[0] % n
    if v != r:
        return _reject(trace, "x1 mod n != r", "require v = x1 mod n = r",
                       x1=_fmt(X[0]), v=_fmt(v), r=_fmt(r))
    add_step(trace, "VALID: x1 mod n == r", "v = x1 mod n = r", x1=_fmt(X[0]), v=_fmt(v), r=_fmt(r))
    return True


def verify(
    pub: "PublicKey",
    msg: bytes,
    sig: "Signature",
    hash_name: str = "sha256",
    trace: "Trace | None" = None,
) -> bool:
    """Return True iff ``sig`` is a valid ECDSA signature on ``msg`` under ``pub``.

    Steps: check 1 <= r, s <= n-1; check Q is on the curve and not O;
    e = hash(msg); w = s^-1 mod n; u1 = e*w mod n; u2 = r*w mod n;
    (x1, y1) = u1*G + u2*Q; reject if O; valid iff x1 mod n == r.

    Never raises: any failed check returns False and records the reason
    (e.g. "r out of range", "x1 mod n != r") in the trace.
    """
    try:
        if not _check_inputs(pub, sig, trace):
            return False
        e = hash_message(msg, pub.curve, hash_name, trace)
        return _verify_digest(pub, e, sig, trace)
    except Exception as exc:  # noqa: BLE001 - verify must never raise
        return _reject(trace, f"error during verification ({type(exc).__name__}: {exc})")


def verify_file(
    pub: "PublicKey",
    path: str | PathLike,
    sig: "Signature",
    hash_name: str = "sha256",
    trace: "Trace | None" = None,
) -> bool:
    """Like :func:`verify`, but hashes the file at ``path`` with P3's hash_file."""
    try:
        if not _check_inputs(pub, sig, trace):
            return False
        try:
            e = hash_file(path, pub.curve, hash_name, trace)
        except OSError as exc:
            return _reject(trace, f"could not read file ({exc.strerror or exc})", path=str(path))
        return _verify_digest(pub, e, sig, trace)
    except Exception as exc:  # noqa: BLE001 - verify must never raise
        return _reject(trace, f"error during verification ({type(exc).__name__}: {exc})")


def explain_verify_math() -> str:
    """Short plain-text proof of why verification works:
    u1*G + u2*Q = (e + r*d) * s^-1 * G = k*G.
    """
    return (
        "Why verification works\n"
        "\n"
        "The signer picked a secret nonce k, computed R = k*G and r = x(R) mod n, and\n"
        "    s = k^-1 * (e + r*d) mod n.\n"
        "Rearranging gives  k = s^-1 * (e + r*d) = w * (e + r*d) mod n.\n"
        "\n"
        "The verifier only knows Q = d*G, not d. It computes\n"
        "    u1*G + u2*Q = (e*w)*G + (r*w)*(d*G)\n"
        "                = w*(e + r*d) * G\n"
        "                = k*G\n"
        "                = R.\n"
        "\n"
        "So the x-coordinate of u1*G + u2*Q, reduced mod n, equals r exactly when the\n"
        "signature was made with the private key d for this message hash e.\n"
        "Change the message, r, s or the key, and the point lands somewhere else."
    )
